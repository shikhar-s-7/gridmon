"""Docs: regenerate the results block of README.md from reports/results.json (and the C/port reports), so the
landing page carries no hand-typed result numbers. The block lies between `<!-- results:start -->` and
`<!-- results:end -->`.

Usage: python scripts/update_readme.py [--check]   (--check: exit 1 if README.md is not current)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- results:start -->", "<!-- results:end -->"
NAMES = {"rules": "Rules (standards-based)", "gbm_embedded": "GBM-embedded (13.6 KB, C core)",
         "gbm_unconstrained": "GBM-unconstrained (reference)"}


def block() -> str:
    r = json.loads((ROOT / "reports" / "results.json").read_text())
    m6 = json.loads((ROOT / "reports" / "m6_sil.json").read_text())
    m7 = json.loads((ROOT / "reports" / "m7_port_stream.json").read_text())["main_LL_calibrated"]["summary"]
    rows = ["| method | test_iid macro-F1 | test_shift macro-F1 | iid -> shift (95 % CI) | false alarms iid / shift |",
            "|---|---|---|---|---|"]
    for m, name in NAMES.items():
        a = r["per_split"]["test_iid"]["methods"][m]
        b = r["per_split"]["test_shift"]["methods"][m]
        d = r["iid_to_shift"][m]

        def f(x: dict) -> str:
            return f"{x['mean']:.4f}" + (f" +/- {x['sd']:.4f}" if x["sd"] > 0 else "")
        rows.append(f"| {name} | {f(a['macro_f1'])} | {f(b['macro_f1'])} | {d['change']:+.3f} [{d['ci95'][0]:+.3f}, "
                    f"{d['ci95'][1]:+.3f}] | {100 * a['false_alarm_rate']['mean']:.1f} % / {100 * b['false_alarm_rate']['mean']:.1f} % |")
    c_iid = r["per_split"]["test_iid"]["comparisons"]["gbm_embedded_minus_rules"]["bootstrap"]
    c_sh = r["per_split"]["test_shift"]["comparisons"]["gbm_embedded_minus_rules"]["bootstrap"]
    sil = m6["splits"]
    n_agree = sum(v["rules"]["label_agree"] for v in sil.values())
    n_all = sum(v["n_records"] for v in sil.values())
    lines = [START, "", "Sealed test evaluation (one run of the frozen methods; ML = mean +/- sd over 3 seeds) [SIM]:", "",
             *rows, "",
             f"GBM-embedded minus rules: test_iid {c_iid['diff_seed_mean']:+.4f} (95 % CI [{c_iid['ci95_seed_mean'][0]:+.4f}, "
             f"{c_iid['ci95_seed_mean'][1]:+.4f}], not significant); test_shift {c_sh['diff_seed_mean']:+.4f} "
             f"([{c_sh['ci95_seed_mean'][0]:+.4f}, {c_sh['ci95_seed_mean'][1]:+.4f}], rules significantly better).",
             f"C core vs Python: rule labels equal on {n_agree:,}/{n_all:,} val/test/train records, golden vectors "
             f"{m6['golden']['n_pass']}/{m6['golden']['n_files']}, working state {m6['memory']['sizeof_gm_ctx_t_bytes']:,} B. "
             f"C2000 port-layer stream test: {m7['events_triggered']}/{m7['events']} events captured, "
             f"{m7['false_triggers_outside_events']} false triggers, {m7['overruns']} overruns.",
             "_Generated by scripts/update_readme.py from reports/results.json, m6_sil.json and m7_port_stream.json._", "", END]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    p = ROOT / "README.md"
    txt = p.read_text(encoding="utf-8")
    if START not in txt or END not in txt:
        print("README.md has no results block markers")
        return 1
    new = txt[:txt.index(START)] + block() + txt[txt.index(END) + len(END):]
    if args.check:
        print("README.md results block is current" if new == txt else "README.md results block is out of date")
        return 0 if new == txt else 1
    p.write_text(new, encoding="utf-8", newline="\n")
    print("README.md results block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
