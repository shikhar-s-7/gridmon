"""M7 (L3 preparation): write firmware/c2000/pil_launchpad/pil_records.{h,c} for the UNTESTED LaunchPad PIL
template: three golden records (sag_unbal, phase_jump, freq_event) as const int16 arrays plus the expected
outputs of the host C core (L1): rule label/reason, GBM label and the 37 features (float32 hex literals),
so the target can report its label match and its feature deviation from L1.

Usage: python scripts/make_pil_records.py [--check]   (--check: exit 1 if the committed files differ)
"""

from __future__ import annotations

import argparse
import sys

import numpy as np

from gridmon.c_sil import CCore
from gridmon.io import ROOT

FILES = ("07_val_sag_unbal_0012.npz", "13_val_phase_jump_0020.npz", "16_val_freq_event_0004.npz")
OUT = ROOT / "firmware" / "c2000" / "pil_launchpad"


def _hexf(v: float) -> str:
    x = float(np.float32(v))
    if x == 0.0:
        return "0x0p+0f"
    s = x.hex()
    sign = "-" if s.startswith("-") else ""
    mant, exp = s.lstrip("-")[2:].split("p")
    ip, fp = mant.split(".") if "." in mant else (mant, "")
    fp = fp.rstrip("0")
    return f"{sign}0x{ip}{'.' + fp if fp else ''}p{exp}f"


def _split_features(text: str) -> tuple[str, np.ndarray]:
    key = "const float pil_expect_features[PIL_N_RECORDS][37] = {"
    if key not in text:
        return text, np.zeros(0)
    head, rest = text.split(key, 1)
    block, tail = rest.split("};", 1)
    vals = np.array([float.fromhex(v.strip().rstrip("f")) for v in block.replace("{", "").replace("}", "").split(",")
                     if v.strip()])
    return head + key + tail, vals


def _same(a: str, b: str) -> bool:
    ta, va = _split_features(a)
    tb, vb = _split_features(b)
    return ta == tb and va.shape == vb.shape and bool(np.allclose(va, vb, rtol=1e-5, atol=1e-6))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    core = CCore()
    recs = []
    for f in FILES:
        g = np.load(ROOT / "golden" / f, allow_pickle=False)
        x = np.ascontiguousarray(g["x"], dtype=np.int16)
        r = core.process(x[None])
        recs.append((f, x, r))
    OUT.mkdir(parents=True, exist_ok=True)
    h = ["/* GENERATED by scripts/make_pil_records.py from golden/ and the host C core (L1). Do not edit.",
         " * Simulation-only records for the UNTESTED LaunchPad PIL template. */",
         "#ifndef PIL_RECORDS_H", "#define PIL_RECORDS_H", "", "#include <stdint.h>", "",
         f"#define PIL_N_RECORDS {len(recs)}", "#define PIL_N_SAMPLES 15000  /* 3 x 5000, planar ab | bc | ca */",
         "#define PIL_LSB_PU (0x1p-10f)", "",
         "extern const int16_t pil_x[PIL_N_RECORDS][PIL_N_SAMPLES];",
         "extern const int16_t pil_expect_rule_label[PIL_N_RECORDS];",
         "extern const int16_t pil_expect_rule_reason[PIL_N_RECORDS];",
         "extern const int16_t pil_expect_gbm_label[PIL_N_RECORDS];",
         "extern const float pil_expect_features[PIL_N_RECORDS][37];",
         "extern const char *const pil_names[PIL_N_RECORDS];", "", "#endif /* PIL_RECORDS_H */", ""]
    c = ["/* GENERATED by scripts/make_pil_records.py. Do not edit. Simulation-only. */", '#include "pil_records.h"', "",
         "const int16_t pil_x[PIL_N_RECORDS][PIL_N_SAMPLES] = {"]
    for f, x, _ in recs:
        vals = [str(int(v)) for v in x.reshape(-1)]
        c.append(f"    {{ /* {f} */")
        c += ["        " + ", ".join(vals[i:i + 20]) + "," for i in range(0, len(vals), 20)]
        c.append("    },")
    c.append("};\n")
    c.append("const int16_t pil_expect_rule_label[PIL_N_RECORDS] = {" + ", ".join(str(int(r["rule_label"][0])) for *_, r in recs) + "};")
    c.append("const int16_t pil_expect_rule_reason[PIL_N_RECORDS] = {" + ", ".join(str(int(r["rule_reason"][0])) for *_, r in recs) + "};")
    c.append("const int16_t pil_expect_gbm_label[PIL_N_RECORDS] = {" + ", ".join(str(int(r["gbm_label"][0])) for *_, r in recs) + "};")
    c.append("const float pil_expect_features[PIL_N_RECORDS][37] = {")
    for *_, r in recs:
        c.append("    {" + ", ".join(_hexf(v) for v in r["features_raw"][0]) + "},")
    c.append("};")
    c.append("const char *const pil_names[PIL_N_RECORDS] = {" + ", ".join(f'"{f[:-4]}"' for f, *_ in recs) + "};\n")
    texts = {OUT / "pil_records.h": "\n".join(h), OUT / "pil_records.c": "\n".join(c)}
    if args.check:  # exact text, except the expected features: numeric (libm may differ by an ulp per platform)
        bad = [p.name for p, s in texts.items() if not p.exists() or not _same(p.read_text(encoding="utf-8"), s)]
        print("differs: " + ", ".join(bad) if bad else "pil_records up to date")
        return 1 if bad else 0
    for p, s in texts.items():
        p.write_text(s, encoding="utf-8", newline="\n")
    for f, _, r in recs:
        print(f"{f}: rule {r['rule_label_name'][0]} ({int(r['rule_reason'][0])}), gbm {int(r['gbm_label'][0])}")
    print(f"-> {OUT.relative_to(ROOT)}/pil_records.{{h,c}}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
